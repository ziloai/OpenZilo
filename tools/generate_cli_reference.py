"""Auto-generate CLI command reference Markdown directly from openzilo._cli.build_parser().

Run with:
    uv run python tools/generate_cli_reference.py
"""

from __future__ import annotations

import argparse
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from openzilo._cli import build_parser  # noqa: E402


def _iter_commands(parser: argparse.ArgumentParser, prefix: str = "openzilo"):
    """Yield (full_command, help_text, subparser) in definition order."""
    subparsers_action = next(
        (a for a in parser._actions if isinstance(a, argparse._SubParsersAction)),
        None,
    )
    if subparsers_action is None:
        return
    help_by_name = {
        action.dest: (action.help or "")
        for action in subparsers_action._choices_actions
    }
    for name, sub in subparsers_action.choices.items():
        full = f"{prefix} {name}"
        nested = next(
            (a for a in sub._actions if isinstance(a, argparse._SubParsersAction)),
            None,
        )
        if nested is not None:
            yield from _iter_commands(sub, full)
        else:
            yield full, help_by_name.get(name, sub.description or ""), sub


def _format_default(action: argparse.Action) -> str:
    if action.default is argparse.SUPPRESS or action.default is None or action.default is False:
        return "-"
    return f"`{action.default}`"


def _format_arg_name(action: argparse.Action) -> str:
    if action.option_strings:
        flags = ", ".join(f"`{opt}`" for opt in action.option_strings)
        if action.metavar:
            return f"{flags} `{action.metavar}`"
        return flags
    return f"`{action.dest}`"


def _render(locale: str) -> str:
    parser = build_parser()
    commands = list(_iter_commands(parser))

    if locale == "zh-CN":
        lines = [
            "# CLI 命令参考",
            "",
            "本页由 `tools/generate_cli_reference.py` 直接从 `openzilo._cli.build_parser()` 自动生成，列出当前版本全部 CLI 子命令、参数与选项。",
            "",
            "安装或直接运行：",
            "",
            "```sh",
            "uv tool install openzilo",
            "openzilo --help",
            "",
            "# 或免安装直接运行",
            "uvx openzilo --help",
            "```",
            "",
            "## 命令总览",
            "",
            "| 命令 | 说明 |",
            "| :--- | :--- |",
        ]
    else:
        lines = [
            "# CLI Command Reference",
            "",
            "Auto-generated by `tools/generate_cli_reference.py` directly from `openzilo._cli.build_parser()`, listing every subcommand, positional argument, and option.",
            "",
            "Install or run directly:",
            "",
            "```sh",
            "uv tool install openzilo",
            "openzilo --help",
            "",
            "# Or run without installing",
            "uvx openzilo --help",
            "```",
            "",
            "## Command Summary",
            "",
            "| Command | Description |",
            "| :--- | :--- |",
        ]

    for full, summary, _ in commands:
        anchor = full.lower().replace(" ", "-")
        lines.append(f"| [`{full}`](#{anchor}) | {summary} |")

    lines.append("")
    lines.append("## 命令详情" if locale == "zh-CN" else "## Command Details")
    lines.append("")

    for full, summary, sub in commands:
        lines.append(f"### {full}")
        lines.append("")
        if summary:
            lines.append(summary)
            lines.append("")
        usage = sub.format_usage().strip()
        if usage.startswith("usage: "):
            usage = usage[len("usage: "):]
        # Replace script basename with canonical command prefix
        usage_tokens = usage.split()
        cmd_tokens = full.split()
        if usage_tokens and len(usage_tokens) >= len(cmd_tokens):
            usage = " ".join(cmd_tokens + usage_tokens[len(cmd_tokens):])
        lines.append("```sh")
        lines.append(usage)
        lines.append("```")
        lines.append("")

        actions = [
            a for a in sub._actions
            if not isinstance(a, (argparse._HelpAction, argparse._VersionAction, argparse._SubParsersAction))
        ]
        if actions:
            if locale == "zh-CN":
                lines.append("| 参数 / 选项 | 可选值 | 默认值 | 说明 |")
            else:
                lines.append("| Argument / Option | Choices | Default | Description |")
            lines.append("| :--- | :--- | :--- | :--- |")
            for action in actions:
                choices = ", ".join(f"`{c}`" for c in action.choices) if action.choices else "-"
                help_text = (action.help or "").replace("|", "\\|").replace("\n", " ").strip() or "-"
                lines.append(
                    f"| {_format_arg_name(action)} | {choices} | {_format_default(action)} | {help_text} |"
                )
            lines.append("")

    return "\n".join(lines).rstrip() + "\n"


def main() -> None:
    docs_dir = ROOT / "docs"
    (docs_dir / "cli-reference.en.md").write_text(_render("en"), encoding="utf-8")
    (docs_dir / "cli-reference.zh-CN.md").write_text(_render("zh-CN"), encoding="utf-8")
    print("Generated docs/cli-reference.en.md and docs/cli-reference.zh-CN.md")


if __name__ == "__main__":
    main()
